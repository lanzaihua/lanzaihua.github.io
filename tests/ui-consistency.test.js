'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

test('visible copy uses the current storage backend and review facts', () => {
  const library = read('src/js/30-library.js');
  const stats = read('src/js/16-stats.js');
  const editor = read('src/js/40-editor.js');
  const direct = read('src/js/46-direct-ai.js');
  assert.ok(!/D1 至 D365/.test(library), '规范页仍写 D1 至 D365，和 20–32 个节点矛盾');
  assert.ok(/20–32/.test(library) && /D1 至 D1800/.test(library), '规范页缺少真实复习节点范围');
  const shell = read('src/js/15-shell.js');
  assert.ok(!/D365|D1\/3\/7\/15\/30/.test(library + shell), '当前界面仍残留旧的 D365 / D1-3-7-15-30 节奏');
  assert.ok(/D1…D1800/.test(shell), '复习行没有显示 D1…D1800 的真实跨度');
  assert.ok(!/数据默认保存在浏览器 localStorage/.test(library), '规范页仍把主存储写成 localStorage');
  assert.ok(/IndexedDB/.test(library) && /IndexedDB/.test(stats), '规范或统计页没有写明 IndexedDB');
  assert.ok(/AES-GCM/.test(editor) && /IndexedDB/.test(editor), '设置页密钥说明没有写明 AES-GCM / IndexedDB');
  assert.ok(!/token 只存本机 localStorage/.test(direct), '直连 AI 注释仍写 localStorage');
  assert.ok(!/内置 8825/.test(library), '题库注释仍是旧的 8825 题');
  const notes = read('src/js/49-notes.js');
  assert.ok(/<\/b> 本<\/span>/.test(notes) && /<\/b> 条 <span class="page-nb">知识笔记/.test(notes), '笔记库没有统一本 / 条计数口径');
  assert.ok(/\.hero-side-empty\b/.test(read('src/styles.css')), '总览空进度卡片缺少样式');
});

test('latest update block and README share the same date, counts and current facts', () => {
  const changelog = read('src/js/48-changelog.js');
  const sandbox = { window: {}, document: { addEventListener() {}, querySelector() { return null; }, querySelectorAll() { return []; }, getElementById() { return null; } }, console };
  vm.runInNewContext(changelog + '\n;globalThis.__UPDATE_LOG__ = UPDATE_LOG;', sandbox, { filename: '48-changelog.js' });
  const latest = sandbox.__UPDATE_LOG__[0];
  const latestText = JSON.stringify(latest);
  assert.strictEqual(latest.date, '2026-11-18');
  assert.strictEqual(latest.title, '计划顺序与智能读题');
  assert.strictEqual(latest.items.length, 9);
  assert.ok(latest.items.some((row) => row.group === '计划顺序'), '最新更新块缺少计划顺序');
  assert.ok(latest.items.some((row) => row.group === '读题排程'), '最新更新块缺少读题排程');
  assert.ok(latest.items.some((row) => row.group === '留白网格'), '最新更新块缺少留白网格');
  assert.ok(latest.items.some((row) => row.group === '字体层级'), '最新更新块缺少字体层级');
  assert.ok(latest.items.some((row) => row.group === '用时口径'), '最新更新块缺少用时口径');
  assert.ok(latest.items.some((row) => row.group === '记忆用法'), '最新更新块缺少记忆用法');
  assert.strictEqual(latest.notifyItems.length, 9);
  assert.ok(!/99 项|题库仍为 9163|1900 余字|v2026\.11\.15|证明成立（详见标准解答）|按 4MB 预算检查/.test(latestText), '最新更新块仍含旧的同日数值');
  assert.ok(latest.notifyItems.every((it) => latest.items.some((row) => row.group === it.group)), '通知分组不在最新更新记录中');
  const readme = read('README.md');
  assert.ok(readme.includes('### 2026-11-18 · 计划顺序与智能读题'), 'README 最新更新块日期或标题不一致');
  assert.ok(readme.includes('### 2026-11-17 · 复习计划与记录收口'), 'README 缺少 11-17 更新块');
  assert.ok(readme.includes('**9 项 · 9 组**'), 'README 最新更新块计数不一致');
  assert.ok(readme.includes('| **留白网格** |'), 'README 最新更新块缺少留白网格行');
  assert.ok(readme.includes('| **字体层级** |'), 'README 最新更新块缺少字体层级行');
  assert.ok(readme.includes('| **用时口径** |'), 'README 最新更新块缺少用时口径行');
  assert.ok(readme.includes('| **记忆用法** |'), 'README 最新更新块缺少记忆用法行');
  assert.ok(readme.includes('**公式细节**'), 'README 最新更新块缺少公式细节');
  assert.ok(readme.includes('| **计划顺序** |'), 'README 最新更新块缺少计划顺序行');
  assert.ok(readme.includes('| **读题排程** |'), 'README 最新更新块缺少读题排程行');
  assert.ok(readme.includes('### 2026-11-15 · 题库扩充与稳定性加固'), 'README 缺少 11-15 更新块');
  assert.ok(/历史更新 · 2026-11-17 及更早 · 26 个版本/.test(readme), 'README 历史折叠版本数不是 26');
  assert.strictEqual(sandbox.__UPDATE_LOG__.filter((b) => b.date === '2026-11-15').length, 1, '11-15 更新块只能有一块');
  assert.ok(readme.includes('默认 IndexedDB'), 'README 数据方式仍写 localStorage');
  const changelogMd = read('CHANGELOG.md');
  assert.ok(changelogMd.includes('## 计划顺序与智能读题\n\n2026-11-18\n\n**9 项 · 9 组**'), 'CHANGELOG 最新块未同步');
  assert.ok(changelogMd.includes('## 复习计划与记录收口\n\n2026-11-17\n\n**6 项 · 6 组**'), 'CHANGELOG 缺少 11-17 块');
  assert.ok(changelogMd.includes('## 题库扩充与稳定性加固\n\n2026-11-15\n\n**32 项 · 32 组**'), 'CHANGELOG 缺少 11-15 更新块');
});
