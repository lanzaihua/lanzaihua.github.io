const groups = {
  deriv: base.derivGroup,
  limit: base.limitGroup,
  integral: base.integralGroup,
  series: base.seriesGroup,
  complete: completeGroup,
  uniform: uniformGroup
};
function buildNumeric2(kind, k) {
  const g = groups[kind];
  if (!g) throw new Error('未知数值模块 ' + kind);
  return g(k);
}
module.exports = { buildNumeric2, completeGroup, uniformGroup };